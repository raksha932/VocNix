import fetch from 'node-fetch';

const BASE_URL = 'http://localhost:3000';

async function runTests() {
  console.log('====================================================');
  console.log('  TESTING MULTILINGUAL AUDIENCE LINKS & RESTRICTIONS');
  console.log('====================================================\n');

  // 1. Get or create an event with Tamil, Hindi, Telugu, Malayalam
  console.log('Step 1: Fetching existing events...');
  const eventsRes = await fetch(`${BASE_URL}/api/events`);
  const eventsData = await eventsRes.json();

  let targetEvent = null;
  const targetLanguages = ['ta', 'hi', 'te', 'ml'];

  if (eventsData.success && eventsData.events?.length > 0) {
    for (const evt of eventsData.events) {
      const codes = (evt.languages || []).map((l) => l.language_code?.toLowerCase());
      const hasAll = targetLanguages.every((code) => codes.includes(code));
      if (hasAll && evt.status !== 'ended') {
        targetEvent = evt;
        break;
      }
    }
  }

  if (!targetEvent) {
    console.log('No existing 4-language event found. Creating a test event...');
    const createRes = await fetch(`${BASE_URL}/api/events`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        title: 'Global Multilingual Summit (Tamil, Hindi, Telugu, Malayalam)',
        description: 'Automated test event for strict multilingual audience isolation',
        scheduled_start: new Date().toISOString(),
        languages: [
          { code: 'ta', name: 'Tamil' },
          { code: 'hi', name: 'Hindi' },
          { code: 'te', name: 'Telugu' },
          { code: 'ml', name: 'Malayalam' },
        ],
      }),
    });
    const createData = await createRes.json();
    if (!createData.success || !createData.event) {
      throw new Error(`Failed to create test event: ${createData.error}`);
    }
    targetEvent = createData.event;
    console.log(`✓ Created test event: "${targetEvent.title}" (ID: ${targetEvent.id})`);
  } else {
    console.log(`✓ Found existing test event: "${targetEvent.title}" (ID: ${targetEvent.id})`);
  }

  console.log(`Public Access Token: ${targetEvent.public_access_token}\n`);

  // 2. Test each language translator link & audience link
  console.log('Step 2: Testing Translator Link -> Audience Link mappings:');

  for (const langCode of targetLanguages) {
    const lang = targetEvent.languages.find(
      (l) => l.language_code?.toLowerCase() === langCode
    );
    const room = targetEvent.rooms.find(
      (r) => r.event_language_id === lang.id
    );

    if (!room) {
      throw new Error(`Room missing for language: ${langCode}`);
    }

    console.log(`\n--- Testing ${lang.language_name} (${langCode.toUpperCase()}) ---`);
    console.log(`  Translator Secure Token: ${room.secure_room_token}`);
    console.log(`  LiveKit Room Name: ${room.livekit_room_name}`);

    // Fetch translator room metadata
    const roomRes = await fetch(`${BASE_URL}/api/livekit/translator-token`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ roomToken: room.secure_room_token }),
    });
    const roomData = await roomRes.json();
    if (!roomData.success) {
      throw new Error(`Failed to fetch translator token for ${langCode}: ${roomData.error}`);
    }

    // Verify audienceUrl format generated by translator
    const expectedAudienceUrl = `/listen/${targetEvent.public_access_token}?lang=${langCode}`;
    console.log(`  ✓ Generated Audience Link: ${expectedAudienceUrl}`);

    // Call /api/audience/event/[token]?lang=[langCode]
    const audEventRes = await fetch(
      `${BASE_URL}/api/audience/event/${targetEvent.public_access_token}?lang=${langCode}`
    );
    const audEventData = await audEventRes.json();
    if (!audEventData.success) {
      throw new Error(`Failed to fetch audience event data for ${langCode}: ${audEventData.error}`);
    }

    if (audEventData.lockedRoomId !== room.id) {
      throw new Error(
        `FAIL: Expected lockedRoomId to be ${room.id} for ${langCode}, got ${audEventData.lockedRoomId}`
      );
    }
    console.log(`  ✓ /api/audience/event returned lockedRoomId: ${audEventData.lockedRoomId} matching ${lang.language_name}`);

    // Request audience token for this language
    const audTokenRes = await fetch(`${BASE_URL}/api/livekit/audience-token`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        eventToken: targetEvent.public_access_token,
        roomId: room.id,
        languageCode: langCode,
      }),
    });
    const audTokenData = await audTokenRes.json();
    if (!audTokenData.success) {
      throw new Error(`Failed to generate audience token for ${langCode}: ${audTokenData.error}`);
    }

    if (audTokenData.room?.livekitRoomName !== room.livekit_room_name) {
      throw new Error(
        `FAIL: LiveKit room name mismatch! Expected ${room.livekit_room_name}, got ${audTokenData.room?.livekitRoomName}`
      );
    }
    console.log(`  ✓ LiveKit Audience Token issued successfully`);
    console.log(`    - wsUrl: ${audTokenData.wsUrl}`);
    console.log(`    - Language: ${audTokenData.room.languageName}`);
    console.log(`    - LiveKit Room: ${audTokenData.room.livekitRoomName}`);

    // Test tamper protection: try to request this room with WRONG language code
    const wrongLangCode = langCode === 'ta' ? 'hi' : 'ta';
    const tamperRes = await fetch(`${BASE_URL}/api/livekit/audience-token`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        eventToken: targetEvent.public_access_token,
        roomId: room.id,
        languageCode: wrongLangCode,
      }),
    });
    const tamperData = await tamperRes.json();
    if (tamperRes.status !== 400) {
      throw new Error(`FAIL: Tamper attempt with mismatched language was NOT rejected! Status: ${tamperRes.status}`);
    }
    console.log(`  ✓ Tamper Protection verified: Requesting ${lang.language_name} room with '${wrongLangCode}' was correctly rejected (${tamperData.error})`);
  }

  console.log('\n====================================================');
  console.log('✓ ALL 4 LANGUAGES (TAMIL, HINDI, TELUGU, MALAYALAM)');
  console.log('  PASSED AUDIENCE LINK & WEBRTC VALIDATION 100%!');
  console.log('====================================================');
}

runTests().catch((err) => {
  console.error('\n❌ Test Failed:', err);
  process.exit(1);
});
